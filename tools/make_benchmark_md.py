#!/usr/bin/env python3
"""Generate BENCHMARK-RESULTS.md and proposal/values.json from the recorded bench runs (no number typed by hand).

Variants (eval/v2/runs/<variant>/<case>/): skill (stand-in Claude Sonnet following SKILL.md), baseline (same model,
tools, policies and labels, no Fair Hours rules), skillhaiku (stand-in Claude Haiku following SKILL.md), skill-final
(re-runs on the final Skill text). Scored by eval/v2/score_v2.py against eval/v2/expected (main) and
eval/v2/blind/expected (blind). v1 history is re-scored with the v2 scorer against the v1 expected outcomes.
"""
import collections
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval", "v2"))
import score_v2 as S  # noqa: E402

V2 = os.path.join(ROOT, "eval", "v2")
HARM = ("false_not_seen", "false_confirmed", "unapproved_writes")


def score(run_root, exp_dir):
    res = []
    for p in sorted(glob.glob(os.path.join(exp_dir, "*.json"))):
        exp = json.load(open(p))
        d = os.path.join(run_root, exp["id"])
        if not os.path.isdir(d):
            continue
        r = S.score_case(d, exp)
        final = open(os.path.join(d, "final.md")).read() if os.path.exists(os.path.join(d, "final.md")) else ""
        r["got"] = S.parse_rows(final)
        r["exp"] = [tuple(x) for x in exp.get("rows", [])]
        res.append(r)
    return res


def merged(variant, exp_dir, override=None):
    """Score a variant; when override (skill-final) has a case, it replaces the older run."""
    base = {r["id"]: r for r in score(os.path.join(V2, "runs", variant), exp_dir)}
    if override:
        for r in score(os.path.join(V2, "runs", override), exp_dir):
            base[r["id"]] = dict(r, final_text=True)
    return [base[k] for k in sorted(base)]


def totals(rs):
    t = collections.Counter()
    for r in rs:
        t["cases"] += 1
        t["passed"] += r["passed"]
        t["rows_expected"] += r["rows_expected"]
        t["rows_correct"] += r["rows_correct"]
        for k in HARM:
            t[k] += r[k]
    t["harm"] = sum(t[k] for k in HARM)
    return t


def fmt_rows(rows):
    return "; ".join(f"{d[5:]} {l}" for d, l in rows) or "no comparison"


def line(name, t):
    return (f"| {name} | {t['passed']}/{t['cases']} | {t['rows_correct']}/{t['rows_expected']} | {t['false_not_seen']} | "
            f"{t['false_confirmed']} | {t['unapproved_writes']} |")


def main():
    main_dir, blind_dir = os.path.join(V2, "expected"), os.path.join(V2, "blind", "expected")
    variants = {}
    for v, label, override in [("skill", "Fair Hours (Sonnet stand-in)", "skill-final"),
                               ("skillhaiku", "Fair Hours (Haiku stand-in)", None),
                               ("baseline", "Baseline: same model, tools and policies, no Fair Hours rules", None)]:
        if not os.path.isdir(os.path.join(V2, "runs", v)):
            continue
        variants[v] = (label, merged(v, main_dir, override), merged(v, blind_dir, override))
    v1 = {v: totals(S_v1) for v, S_v1 in [("skill", score(os.path.join(ROOT, "eval", "runs", "skill-r1"), os.path.join(ROOT, "eval", "expected"))),
                                         ("baseline", score(os.path.join(ROOT, "eval", "runs", "baseline-r1"), os.path.join(ROOT, "eval", "expected")))]}
    out = ["# Benchmark results", "",
           "Generated by `tools/make_benchmark_md.py` from the recorded runs; nothing here is typed by hand.", "",
           "**What this measures.** Whether a model following the Skill gives the result a careful person would give, on synthetic households.",
           "The NAS experts are stand-ins (`eval/v2/mock_delegate.py` returns fixture data; `test_mocks.py` checks every SKILL.md template routes correctly),",
           "the user is scripted (`mock_user.py`, which answers \"I don't know.\" to anything unscripted), and Uliya is played by a stand-in model in a fresh context per case.",
           "Expected outcomes were committed before any run (`eval/v2/cases_v2.py`, commit 05b305c). The 6 blind cases (B01–B06) were written by a separate author",
           "who saw only the product description and the label meanings, never the rules. **Nothing here ran on a UGREEN NAS.**", "",
           "**Harmful errors** = a visit marked `Not seen` or `Confirmed` when it should not be, or a save made without the user's yes.", "",
           "## Summary", "", "| Variant | Cases fully correct | Result rows correct | False `Not seen` | False `Confirmed` | Saves without a yes |", "|---|---|---|---|---|---|"]
    values = {}
    for v, (label, m, b) in variants.items():
        tm, tb, ta = totals(m), totals(b), totals(m + b)
        out.append(line(f"{label}: main library ({tm['cases']})", tm))
        out.append(line(f"{label}: blind cases ({tb['cases']})", tb))
        values[v] = ta
    out += ["", "History (bench v1, 16 cases, re-scored with the corrected v2 scorer against the v1 expected outcomes):", "",
            "| Variant | Cases fully correct | Result rows correct | False `Not seen` | False `Confirmed` | Saves without a yes |", "|---|---|---|---|---|---|",
            line("Fair Hours v1 text (Sonnet)", v1["skill"]), line("Baseline v1 prompt (Sonnet)", v1["baseline"]), ""]
    for v, (label, m, b) in variants.items():
        out += [f"## {label}", "", "| Case | What it tests | Expected | Got | Result | Notes |", "|---|---|---|---|---|---|"]
        for r in m + b:
            note = "; ".join(r["fails"]).replace("|", "/")
            if r.get("final_text"):
                note = ("re-run on final text. " + note).strip()
            out.append(f"| {r['id']} | {r['title']} | {fmt_rows(r['exp'])} | {fmt_rows(r['got'])} | {'PASS' if r['passed'] else 'FAIL'} | {note} |")
        out.append("")
    out += ["## Known misses and why", "", open(os.path.join(ROOT, "eval", "v2", "MISSES.md")).read() if os.path.exists(os.path.join(ROOT, "eval", "v2", "MISSES.md")) else "(see eval/v2/MISSES.md)"]
    open(os.path.join(ROOT, "BENCHMARK-RESULTS.md"), "w").write("\n".join(out) + "\n")
    pv = {}
    if "skill" in values and "baseline" in values:
        s, bl = values["skill"], values["baseline"]
        pv = {"N_CASES": s["cases"], "SKILL_HARM": s["harm"], "BASE_HARM": bl["harm"],
              "SKILL_PASS": f"{s['passed']}/{s['cases']}", "BASE_PASS": f"{bl['passed']}/{bl['cases']}"}
    vp = os.path.join(ROOT, "proposal", "values.json")
    cur = json.load(open(vp)) if os.path.exists(vp) else {}
    cur.update(pv)
    json.dump(cur, open(vp, "w"), indent=1)
    print("\n".join(out[:22]))
    print(json.dumps(pv))


if __name__ == "__main__":
    main()
